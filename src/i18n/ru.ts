// Структура словаря с «расширенными» листьями: каждый строковый литерал
// превращается в string, кортеж — в string[]. Другие языки типизируются этим
// типом, поэтому обязаны иметь те же ключи (но могут нести любые значения).
type Widen<T> = T extends string
  ? string
  : T extends readonly (infer U)[]
  ? Widen<U>[]
  : { -readonly [K in keyof T]: Widen<T[K]> };

export type Dictionary = Widen<typeof ru>;
